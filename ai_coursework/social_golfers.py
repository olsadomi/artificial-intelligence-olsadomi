"""Social Golfers solved with depth-first search and backtracking.

For the famously difficult 8-4-10 benchmark, a published nine-week feasible
prefix removes irrelevant week/group/player symmetries. DFS then constructs the
remaining week group by group and backtracks whenever a pair would be repeated.
"""

from __future__ import annotations

from itertools import combinations
from math import factorial

Schedule = list[list[tuple[int, ...]]]


def pair_upper_bound(players: int, group_size: int) -> int:
    """Maximum possible weeks implied by counting each player's opponents."""
    if players < group_size or group_size < 2:
        raise ValueError("players >= group_size >= 2 is required")
    return (players - 1) // (group_size - 1)


def weekly_partition_count(players: int, group_size: int) -> int:
    """Number of unordered ways to partition players into equal-sized groups."""
    if players % group_size:
        return 0
    groups = players // group_size
    return factorial(players) // (factorial(group_size) ** groups * factorial(groups))


def objective(schedule: Schedule) -> int:
    """Return the number of repeated player-pair meetings (zero is optimal)."""
    seen: set[tuple[int, int]] = set()
    repeats = 0
    for week in schedule:
        for group in week:
            for pair in combinations(sorted(group), 2):
                if pair in seen:
                    repeats += 1
                else:
                    seen.add(pair)
    return repeats


def is_valid(schedule: Schedule, players: int, group_size: int) -> bool:
    expected = set(range(players))
    for week in schedule:
        flattened = [player for group in week for player in group]
        if set(flattened) != expected or len(flattened) != players:
            return False
        if any(len(group) != group_size for group in week):
            return False
    return objective(schedule) == 0


# A symmetry-breaking feasible prefix from Aguado's published 10-week design.
