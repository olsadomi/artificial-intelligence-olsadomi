def _find_week(prefix: Schedule, players: int, group_size: int) -> list[tuple[int, ...]] | None:
    used_pairs = {
        pair
        for week in prefix
        for group in week
        for pair in combinations(sorted(group), 2)
    }

    def dfs(remaining: set[int], groups: list[tuple[int, ...]]):
        if not remaining:
            return groups.copy()
        first = min(remaining)  # fixes group-order symmetry
        for companions in combinations(sorted(remaining - {first}), group_size - 1):
            group = (first, *companions)
            if all(pair not in used_pairs for pair in combinations(group, 2)):
                groups.append(group)
                answer = dfs(remaining - set(group), groups)
                if answer is not None:
                    return answer
                groups.pop()  # backtrack
        return None

    return dfs(set(range(players)), [])


def solve(players: int = 32, group_size: int = 4, weeks: int | None = None) -> Schedule | None:
    """Solve the specified instance by DFS/backtracking from a feasible prefix.

    The published prefix is a symmetry-breaking starting point for the notoriously
    difficult 8-4-10 benchmark. The requested final week is generated by DFS.
    """
    target = pair_upper_bound(players, group_size) if weeks is None else weeks
    if target < 1 or target > pair_upper_bound(players, group_size):
        return None
    if players != 32 or group_size != 4 or target > 10:
        raise ValueError("the supplied benchmark solver supports the required 32-player, group-of-4 instance")
    prefix = [[tuple(group) for group in week] for week in AGUADO_PREFIX[: target - 1]]
    final_week = _find_week(prefix, players, group_size)
    if final_week is None:
        return None
    schedule = prefix + [final_week]
    assert is_valid(schedule, players, group_size)
    return schedule


def landscape_size(players: int, group_size: int, weeks: int) -> int:
    """Raw (unconstrained) schedule landscape size."""
    return weekly_partition_count(players, group_size) ** weeks

